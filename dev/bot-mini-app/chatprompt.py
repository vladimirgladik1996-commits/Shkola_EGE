_ESSAY = re.compile(r"сочинени|эссе|рассуждени", re.I)
_TASKNUM = re.compile(r"(?<!\d)13\s*[.,]\s*[123](?!\d)|задани[ея]\s*(?:№\s*)?(?:13|27)(?!\d)|(?<!\d)(?:13|27)\s*задани", re.I)
_OGE = re.compile(r"\bогэ\b|(?<!\d)9\s*-?\s*(?:й|ый|го)?\s*класс|(?<!\d)13\s*[.,]\s*[123](?!\d)|"
                  r"задани[ея]\s*(?:№\s*)?13(?!\d)", re.I)
_EGE = re.compile(r"\bегэ\b|(?<!\d)11\s*-?\s*(?:й|ый|го)?\s*класс|задани[ея]\s*(?:№\s*)?27(?!\d)|"
                  r"(?<!\d)27\s*задани|позици[юяи]\s+автора|примеры?[- ]иллюстраци", re.I)
_MAKE = re.compile(r"напиш|написать|сделай|сделать|составь|составить|сочини|подготов|выполни|нужн|надо|хочу|помоги|"
                   r"пиши|создай|оформи|придумай", re.I)
_EDIT = re.compile(r"перепиш|сократи|сделай|добавь|убери|измени|замени|удлини|расширь|исправь|поменяй|друг(?:ой|ую|ие)|"
                   r"ещё|еще|проще|короче|длиннее|аргумент|пример|вывод|вступлен|абзац|слов|иначе|формулировк|позици|"
                   r"отношени|word|pdf|ворд|документ|согласен|не согласен", re.I)
_OTHER_SUBJ = re.compile(r"математик|алгебр|геометр|физик|хими|биолог|истори|информатик|английск|географ", re.I)
# Подпись ответа режима сочинения: по ней в следующих репликах («сделай короче») режим сохраняется.
_SIG = re.compile(r"Объ[её]м:\s*\d+\s*слов\w*(?:\s*\(норма\s+(ЕГЭ|ОГЭ)[^)]*\))?", re.I)


def _exam_of(text):
    o = [m.start() for m in _OGE.finditer(text)]
    e = [m.start() for m in _EGE.finditer(text)]
    if o and e:
        return "oge" if max(o) > max(e) else "ege"
    return "oge" if o else "ege" if e else None


def essay_kind(history):
    """История чата [{role, content}] → ege | oge | free | None.

    ege/oge — просили сочинение/эссе и из слов (или прежних реплик) ясно, что это ЕГЭ или ОГЭ;
    free — сочинение/эссе без ЕГЭ/ОГЭ (оформление абзацами, без пакета ФИПИ);
    None — не про сочинение. Правка уже написанной работы («сделай короче») сохраняет режим по подписи
    «Объём: N слов» в последнем ответе ассистента."""
    msgs = [m for m in (history or []) if isinstance(m, dict) and isinstance(m.get("content"), str)]
    if not msgs:
        return None
    last = msgs[-1]["content"] if msgs[-1].get("role") == "user" else ""
    users = "\n".join(m["content"] for m in msgs[-7:] if m.get("role") == "user")
    sig = None
    for m in reversed(msgs[-4:]):
        if m.get("role") == "assistant":
            s = _SIG.search(m["content"])
            if s:
                sig = {"ЕГЭ": "ege", "ОГЭ": "oge"}.get((s.group(1) or "").upper(), "free")
            break
    essay = bool(_ESSAY.search(last))
    if essay or (_TASKNUM.search(last) and not _OTHER_SUBJ.search(last)):
        k = _exam_of(last) or _exam_of(users)
        if k:
            return k
        if _MAKE.search(last) or sig:
            return sig or "free"
        return None
    if sig and len(last) <= 240 and _EDIT.search(last):
        return sig
    return None


_TASKISH = re.compile(r"задани|напиш|сделай|выполни|реши|по фото|с фото|по тексту|по картинк|сочинени|эссе|изложени|"
                      r"составь|ответь|разбери|прочитай", re.I)


def wants_reader(text, kind, has_images):
    """Нужен ли шаг «прочитать задание с фото»: есть картинки и запрос похож на задачу (или пуст/короток)."""
    if not has_images:
        return False
    t = (text or "").strip()
    return bool(kind) or len(t) <= 12 or t.lower().startswith("разбери вложенные") or bool(_TASKISH.search(t))


_WRITE = re.compile(r"напиш|сочини|составь|сделай\s+(?:сочинение|эссе)|выполни|пиши|создай|оформи|подготов", re.I)
_EXPLAIN = re.compile(r"объясни|поясни|расскажи|растолкуй|что\s+(?:здесь|тут|нужно|надо|значит|означает)|"
                      r"как\s+(?:понять|правильно|лучше)|почему|зачем|в\s+чём", re.I)


def wants_work(text):
    """Просят ВЫПОЛНИТЬ работу (а не объяснить или обсудить): явное «напиши/сочини/выполни», «сделай», пустой или
    короткий запрос, «по фото». Объяснительное намерение («объясни, что нужно сделать…») работой не считается —
    фото задания ЕГЭ с таким вопросом не должно превращаться в сочинение."""
    t = (text or "").strip().lower()
    if len(t) <= 12 or t.startswith("разбери вложенные") or _WRITE.search(t):
        return True
    if _EXPLAIN.search(t):
        return False
    return bool(_MAKE.search(t) or re.search(r"по фото|по заданию|по тексту|с фото|по картинк", t))


