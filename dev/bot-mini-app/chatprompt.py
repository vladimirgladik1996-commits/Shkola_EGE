_NOTE = re.compile(r"^\W*примечани[ея]\s*:\s*(.*)$", re.I)


def split_note(text):
    """«ПРИМЕЧАНИЕ: …» из ответа модели → (текст без примечаний, примечание)."""
    body, notes = [], []
    for l in str(text or "").replace("\r", "").split("\n"):
        m = _NOTE.match(l.strip())
        if m:
            notes.append(m.group(1).strip(" *_"))
        else:
            body.append(l)
    return "\n".join(body).strip(), " ".join(n for n in notes if n)


def _titleish(line):
    """Заголовок — короткая строка без точки (вопроса, восклицания, многоточия) в конце: абзац работы так не кончается."""
    l = line.strip()
    return bool(l) and len(l) < 140 and not re.search(r"[.!?…]$", l)


def essay_body(text, fmt):
    """Текст самой работы для подсчёта объёма: без примечаний; в файловых форматах — без заголовка (1-я строка)."""
    body, _ = split_note(text)
    if fmt != "text":
        lines = body.split("\n")
        while lines and not lines[0].strip():
            lines.pop(0)
        if lines and _titleish(lines[0]):          # первая строка — заголовок, если похожа на него; иначе это уже абзац
            lines = lines[1:]
        body = "\n".join(lines)
    return body


def _slov(n):
    """1 слово, 2–4 слова, 5+ слов (11–14 — «слов»)."""
    if n % 10 == 1 and n % 100 != 11:
        return "слово"
    if 2 <= n % 10 <= 4 and not 12 <= n % 100 <= 14:
        return "слова"
    return "слов"


def volume_line(kind, n):
    """Подпись под работой: «Объём: 287 слов (норма ЕГЭ — от 150).» По ней же режим сочинения узнаётся в следующих
    репликах («сделай короче»), поэтому формат менять нельзя без правки _SIG."""
    return "Объём: %d %s%s." % (n, _slov(n), " (%s)" % essaykb.NORM_LABEL[kind] if kind in essaykb.NORM_LABEL else "")


_LISTISH = re.compile(r"^(?:[-•*#>]|\d+[.)]\s|📌|ВОПРОС:|Примечание:|Объём:)", re.I)


def layout(text):
    """Абзацы и красная строка для ТЕКСТОВОГО ответа-сочинения (в пузыре чата white-space: pre-wrap).

    Делает код, а не модель: между абзацами ровно одна пустая строка; переносы внутри абзаца склеены; каждая
    «прозаическая» строка начинается с красной строки (INDENT). Не трогаются: короткие строки без точки в
    конце (заголовок), списки, служебные строки («📌», «Примечание:», «Объём:»). Разметка ** и __ убирается."""
    t = re.sub(r"\*\*|__", "", str(text or "").replace("\r", "")).strip("\n")
    blocks = re.split(r"\n[ \t\u2003\u00a0]*\n", t)
    if len(blocks) == 1:
        lines = [l for l in t.split("\n") if l.strip()]
        if len(lines) > 1:
            blocks = lines                         # модель отделила абзацы одиночным переносом
    out = []
    for b in blocks:
        s = " ".join(x.strip(" \t\u2003\u00a0") for x in b.split("\n") if x.strip())
        s = re.sub(r"[ \t]{2,}", " ", s).strip()
        if not s:
            continue
        service = bool(_LISTISH.match(s)) or (len(s) < 80 and _titleish(s))
        out.append(s if service else INDENT + s)
    return "\n\n".join(out)


