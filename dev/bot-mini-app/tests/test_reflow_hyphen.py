"""Регрессия «ИИ-проверка»: склейка переносов строк в OCR-тексте не должна терять настоящий дефис.
Раньше «кто-»/«нибудь» → «ктонибудь», «по-»/«моему» → «помоему»: ученик видел в «печатной версии»
слово, которого не писал, а проверка находила ложную орфографическую ошибку.
Запуск: python3 tests/test_reflow_hyphen.py"""
import base64, io, os, sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import essaycheck, chatfiles
from PIL import Image

def ok(c): print("  ✓", c)

R = essaycheck._reflow

# --- 1. настоящий дефис сохраняется ---
KEEP = [
    ("Я думаю, что кто-\nнибудь поймёт.", "Я думаю, что кто-нибудь поймёт."),
    ("Он сказал по-\nмоему мнению.", "Он сказал по-моему мнению."),
    ("Что-\nто изменилось.", "Что-то изменилось."),
    ("Говорить по-\nрусски трудно.", "Говорить по-русски трудно."),
    ("Во-\nпервых, это важно.", "Во-первых, это важно."),
    ("Он всё-\nтаки пришёл.", "Он всё-таки пришёл."),
    ("Кое-\nкак справились.", "Кое-как справились."),
    ("Где-\nнибудь рядом.", "Где-нибудь рядом."),
    ("Идти из-\nза угла.", "Идти из-за угла."),
]
for src, want in KEEP:
    got = R(src)
    assert got == want, (src, got, want)
ok("настоящие дефисные слова сохраняются (%d случаев)" % len(KEEP))

# --- 2. обычный перенос по-прежнему склеивается без дефиса ---
JOIN = [
    ("Автор о пере-\nнесённых трудностях.", "Автор о перенесённых трудностях."),
    ("Мы пошли по-\nтому что надо.", "Мы пошли потому что надо."),       # «по-/тому»: НЕ «по-тому»
    ("Мы остались по-\nэтому дома.", "Мы остались поэтому дома."),
    ("Они по-\nехали домой.", "Они поехали домой."),
    ("Это ру-\nка друга.", "Это рука друга."),                              # «ка» — не частица
    ("Это сло-\nво автора.", "Это слово автора."),
]
for src, want in JOIN:
    got = R(src)
    assert got == want, (src, got, want)
ok("обычные переносы склеиваются без дефиса (%d случаев)" % len(JOIN))

# --- 3. идемпотентность и «--» ---
for src, _ in KEEP + JOIN:
    once = R(src)
    assert R(once) == once
ok("_reflow идемпотентна")
assert R("a--\nb") == "a-- b"
ok("двойной дефис не склеивается")

# --- 4. to_jpeg_b64: пределы ---
def jpg(w, h, q=90):
    b = io.BytesIO(); Image.new("RGB", (w, h), (240, 240, 240)).save(b, "JPEG", quality=q); return b.getvalue()
def size(b64): return Image.open(io.BytesIO(base64.b64decode(b64))).size
big = jpg(3500, 2600)
assert max(size(chatfiles.to_jpeg_b64(big))) <= 2600                    # по умолчанию — как раньше (чат)
assert chatfiles.to_jpeg_b64(big, 6000, 19_000_000, 7_500_000) == base64.b64encode(big).decode()  # без пережатия
ok("по умолчанию ≤2600 (чат); для проверки JPEG в пределах идёт без пережатия")
huge = jpg(6000, 5000)                                                 # 30 Мп > 19 Мп
w, h = size(chatfiles.to_jpeg_b64(huge, 6000, 19_000_000, 7_500_000))
assert w * h <= 19_000_000 and abs(w / h - 1.2) < 0.01, (w, h)
ok("сверх 19 Мп — масштаб с сохранением пропорций")
import random
rnd = random.Random(1)
noisy = Image.frombytes("RGB", (1600, 1200), bytes(rnd.getrandbits(8) for _ in range(1600 * 1200 * 3)))
b = io.BytesIO(); noisy.save(b, "PNG")
q_hi = len(base64.b64decode(chatfiles.to_jpeg_b64(b.getvalue(), 6000, 19_000_000, 50_000_000)))
q_lo = len(base64.b64decode(chatfiles.to_jpeg_b64(b.getvalue(), 6000, 19_000_000, 1_000_000)))
assert q_lo < q_hi, (q_lo, q_hi)
ok("лимит по байтам понижает качество ступенями, пока файл не влезет")

print("test_reflow_hyphen: все проверки прошли")
