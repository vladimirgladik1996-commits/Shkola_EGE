"""Буллиты в Word — только для настоящих пунктов списка (баг-репорт 024).

Регресс: парсер принимал тире «—/–» как маркер списка, и любая строка, начинающаяся
с тире (реплики в цитатах, авторские «— …» в сочинениях), превращалась в буллит —
документ усыпан маркированным списком. Стало: буллит/номер — только для строк
с настоящими маркерами «- », «* », «• » или нумерацией «1. »; строка с тире —
обычный абзац. Промты (CHAT_DOC_TAIL / ESSAY_DOC_TAIL) держат то же правило.
Запуск: python3 tests/test_docx_bullets.py
"""
import os, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
import chatfiles


def ok(c):
    print("  ✓", c)


SRC = ("Тест документа\n"
       "Обычная строка — и тире в середине ни на что не влияет.\n"
       "— Это реплика героя в цитате, она НЕ должна стать буллитом.\n"
       "— И вторая реплика подряд — тоже обычный абзац.\n"
       "# Раздел\n"
       "- настоящий пункт списка\n"
       "1. нумерованный пункт\n"
       "• маркер-кружок\n"
       "Ещё обычный абзац.\n")
title, blocks = chatfiles.parse_doc(SRC)
assert title == "Тест документа", title

li = [b for b in blocks if b[0] == "li"]
assert [b[1] for b in li] == ["•", "1.", "•"], li
assert [" ".join(t for t, _ in b[2]) for b in li] == \
       ["настоящий пункт списка", "нумерованный пункт", "маркер-кружок"], li
ok("буллит/номер — только для строк с маркерами «- », «1. », «• »")

paras = [" ".join(t for t, _ in b[1]) for b in blocks if b[0] == "p"]
assert any(p.startswith("— Это реплика") for p in paras), paras
assert any(p.startswith("— И вторая") for p in paras), paras
ok("строки с тире (реплики, цитаты) — обычные абзацы, а не пункты списка")

# --- промты держат правило: тире — не маркер списка ---------------------------
ast = open(os.path.join(ROOT, "assist.py"), encoding="utf-8").read()
cp = open(os.path.join(ROOT, "chatprompt.py"), encoding="utf-8").read()
assert "тире «—» в начале строки" in ast and "не маркер списка" in ast, \
    "CHAT_DOC_TAIL должен объяснять: тире в начале строки — не пункт списка"
assert "тире «—» в начале строки" in cp and "не маркер списка" in cp, \
    "ESSAY_DOC_TAIL должен объяснять: тире в начале строки — не пункт списка"
ok("промты (CHAT_DOC_TAIL / ESSAY_DOC_TAIL) закрепляют правило")

# --- регресс: разметка списка из e9afbc5 (## + пункты) не сломана --------------
title2, blocks2 = chatfiles.parse_doc("Заголовок\n## Подзаголовок\n- пункт один\n- пункт два\n")
assert [b[0] for b in blocks2] == ["h", "li", "li"], blocks2
ok("подзаголовки «##» и настоящие пункты списка работают как раньше")
print("OK")
