# ---------- подсчёт слов по правилам ФИПИ (сноска к демоверсиям ЕГЭ/ОГЭ-2027) ----------
# • служебные и самостоятельные части речи считаются; последовательность слов без пробела — одно слово
#   («всё-таки» — одно, «всё же» — два);
# • инициалы вместе с фамилией — одно слово («М. Ю. Лермонтов», «А.С. Пушкин»);
# • сокращённые слова («т. е.», «т. д.») не считаются; цифры и знаки препинания не считаются
#   («5 лет» — одно слово, «пять лет» — два).
_INITIALS = re.compile(r"^(?:[А-ЯЁA-Z]\.){1,3}$")           # «А.», «А.С.», «М.Ю.»
_ABBR = re.compile(r"^(?:[а-яёa-z]\.){2,4}$")                # «т.е.», «т.д.», «т.п.»
_ABBR_WORDS = frozenset({"т.", "д.", "п.", "е.", "г.", "гг.", "в.", "вв.", "см.", "ср.", "рис.", "стр.", "ул."})
_LETTER = re.compile(r"[А-Яа-яЁёA-Za-z]")
_EDGE = "«»\"'“”„‘’()[]{}<>,;:!?…—–-"


def count_words(text):
    """Число слов по правилам ФИПИ. Нестрока и пустота — 0.

    Инициалы пропускаются только когда за ними следует слово с заглавной буквы (фамилия) или ещё одни
    инициалы: одинокое «я.» в конце предложения — обычное слово и считается."""
    if not isinstance(text, str):
        return 0
    toks = [t.strip(_EDGE) for t in text.replace("\u00a0", " ").replace("\u2003", " ").split()]
    toks = [t for t in toks if t and _LETTER.search(t)]       # цифры, тире, знаки препинания — не слова
    n = 0
    for i, t in enumerate(toks):
        if _ABBR.match(t) or t.lower() in _ABBR_WORDS:
            continue                                         # сокращения не считаются
        if _INITIALS.match(t):
            nxt = toks[i + 1] if i + 1 < len(toks) else ""
            if nxt and (nxt[0].isupper() or _INITIALS.match(nxt)):
                continue                                     # инициалы идут вместе с фамилией
        n += 1
    return n
