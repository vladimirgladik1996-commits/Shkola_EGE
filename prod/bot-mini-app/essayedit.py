"""Правка распознанного текста через Вишенку (экран «Текст проверен», до проверки ошибок).

Ученик выделил в распознанном тексте слово или фрагмент и словами (голосом или текстом) говорит, что с ним сделать:
«замени на … , это неправильно распознано», «удали», «тут ещё слово …». Кими превращает фразу в НОВЫЙ текст выделенного
фрагмента; клиент показывает ответ Вишенки и по «Применить» подменяет фрагмент. Сервер текст не хранит и не правит:
итоговый текст приходит на этап «analyze», где essaycheck.apply_text подгоняет его под слова на фото.

Защиты: модель правит ТОЛЬКО названное учеником (орфографию и пунктуацию не «исправляет» — ошибки ученика ищет
проверка), неясная просьба → вопрос, а не угадывание, ответ валидируется (размер, символы, «ничего не меняется»)."""
import logging
import re

import kimi

log = logging.getLogger("tutor.essayedit")

FRAG_MAX = 1500        # символов в выделенном фрагменте и в его замене
CTX_MAX = 300          # символов контекста до/после фрагмента
INSTR_MAX = 600        # символов во фразе ученика
SAY_MAX = 300
_CTRL = re.compile(r"[\x00-\x08\x0b\x0c\x0e-\x1f\x7f]")

PROMPT = """Ты — Вишенка, помощница ученика в приложении. Ученик сфотографировал рукописное сочинение, система распознала текст, но местами ошиблась. Ученик выделил фрагмент распознанного текста и словами говорит, что с ним сделать.

Выделенный фрагмент: «{fragment}»
Текст перед фрагментом: «{before}»
Текст после фрагмента: «{after}»
Слова ученика: «{instruction}»

Твоя задача — выдать НОВЫЙ текст ВЫДЕЛЕННОГО фрагмента целиком (а не контекста).
Правила:
— выполняй только то, что сказал ученик: заменить слово или часть на названное, удалить, добавить слово, поправить порядок слов. Больше ничего не меняй: не исправляй орфографию и пунктуацию сам — ошибки в работе ученика ищет проверка, это не твоя задача;
— если ученик называет слово так, как оно написано в работе, подставь его буква в букву, даже если оно с ошибкой;
— если непонятно, что и где менять, не угадывай: op="unclear", а в say — один короткий уточняющий вопрос;
— say — коротко от первого лица, что сделаешь, например: «Поняла: заменю «X» на «Y».»; никаких оценок работы.

Ответ — строго JSON без пояснений: {{"op":"replace","replacement":"<новый текст фрагмента>","say":"…"}} или {{"op":"unclear","replacement":"","say":"…"}}"""


def clean(s, n):
    """Строка из запроса → очищенная (без управляющих символов, схлопнутые пробелы), не длиннее n; не строка → ''."""
    if not isinstance(s, str):
        return ""
    return re.sub(r"[ \t]+", " ", _CTRL.sub("", s)).strip()[:n]


def stt_prompt(fragment):
    """Подсказка Whisper: слова выделенного фрагмента — чтобы названное слово не искажалось при распознавании речи."""
    return ("Правка текста сочинения. Фрагмент: " + fragment)[:500]


def _norm(s):
    return " ".join((s or "").split())


def normalize(a, fragment):
    """Ответ модели → {"op": "replace"|"unclear", "replacement": str, "say": str}; любой мусор → unclear."""
    unclear = {"op": "unclear", "replacement": "", "say": "Не поняла, что именно поменять. Скажите, на какое слово заменить?"}
    if not isinstance(a, dict):
        return unclear
    say = clean(a.get("say"), SAY_MAX)
    if a.get("op") != "replace" or not isinstance(a.get("replacement"), str):
        return {**unclear, "say": say or unclear["say"]}
    rep = clean(a["replacement"], FRAG_MAX + 1)
    if len(rep) > FRAG_MAX:
        return unclear
    if _norm(rep) == _norm(fragment):
        return {**unclear, "say": "Так в тексте уже написано. Что нужно поменять?"}
    return {"op": "replace", "replacement": rep, "say": say or ("Поняла: заменю на «%s»." % rep if rep else "Поняла: уберу этот фрагмент.")}


async def interpret(fragment, before, after, instruction):
    """Фраза ученика → {"op","replacement","say"}. Сбой модели — тот же unclear (ничего не меняется)."""
    msg = PROMPT.format(fragment=fragment, before=before, after=after, instruction=instruction)
    try:
        a = await kimi.ask_json([{"role": "user", "content": msg}], max_tokens=600)
    except Exception as e:
        log.warning("essayedit: запрос к Кими не удался: %r", e)
        a = None
    return normalize(a, fragment)
